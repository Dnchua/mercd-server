-- Affected routes: /stages、/areas、/quests、/quests/execute|result 链、
--   /users/preset_data.json（剧情进度字段）。
-- Recovery: 停服 → 一致性备份恢复到新 state 目录 → 配对旧二进制。

-- 第一步：旧 id 抬到 9000xx 临时空间。
