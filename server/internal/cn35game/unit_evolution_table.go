// UnitEvolutionResolved 解析后的进化目标与客户端 evolution_map / evolution_map_desc 结构。
type UnitEvolutionResolved struct {
	ToUnitID int
	NeedInt  map[string]int
	Need     map[string]any
	Desc     map[string]any
}

