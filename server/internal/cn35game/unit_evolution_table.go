// UnitEvolutionRule 查询指定同伴模板 ID 与属性（1..5）的进化配置。
func UnitEvolutionRule(unitID, element int) (UnitEvolutionResolved, bool) {
	entry, ok := unitEvolutionTable[unitID]
	if !ok || entry.ToUnitID <= 0 {
		return UnitEvolutionResolved{}, false
	}
	if element < 1 || element > 5 {
		element = 1
	}
	budID := 5 + element
	flowerID := 10 + element
	budKey := strconv.Itoa(budID)
	flowerKey := strconv.Itoa(flowerID)
	return UnitEvolutionResolved{
		ToUnitID: entry.ToUnitID,
		NeedInt: map[string]int{
			budKey:    entry.BudCount,
			flowerKey: entry.FlowerCount,
		},
		Need: map[string]any{
			budKey:    entry.BudCount,
			flowerKey: entry.FlowerCount,
		},
		Desc: map[string]any{
			budKey:    evolutionBudNames[budID],
			flowerKey: evolutionFlowerNames[flowerID],
		},
	}, true
}

